#!/usr/bin/env python3
"""Write config.js for Prop Log cloud sync from environment variables.

    SUPABASE_ANON_KEY=... python3 tools/make_config.py            # writes ./config.js
    SUPABASE_URL=https://xyz.supabase.co SUPABASE_ANON_KEY=... python3 tools/make_config.py

The anon / publishable key is a PUBLIC client key (Row Level Security protects the data),
so it is fine to ship in config.js. Never put the service_role / secret key here.
The key is never printed.
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
url = os.environ.get('SUPABASE_URL', 'https://ithbhetdbwjmaapmkbcg.supabase.co').rstrip('/')
key = os.environ.get('SUPABASE_ANON_KEY', '').strip()
if not key:
    sys.exit('SUPABASE_ANON_KEY is not set')
if not (key.startswith('eyJ') or key.startswith('sb_publishable_')):
    sys.exit('SUPABASE_ANON_KEY does not look like an anon (eyJ…) or publishable (sb_publishable_…) key')
if key.startswith('sb_secret_') or 'service_role' in key:
    sys.exit('Refusing to embed a secret/service key')
if not re.match(r'^https://[a-z0-9-]+\.supabase\.co$', url):
    sys.exit('SUPABASE_URL looks wrong')
body = ('// Generated by tools/make_config.py – public client config for optional cloud sync.\n'
        '// The publishable/anon key is meant to be public; Row Level Security protects the data.\n'
        'window.PROPLOG_CONFIG = ' + json.dumps({'supabaseUrl': url, 'supabaseKey': key}) + ';\n')
with open(os.path.join(ROOT, 'config.js'), 'w') as f:
    f.write(body)
print('config.js written (%s, key type: %s)' % (url, 'legacy anon JWT' if key.startswith('eyJ') else 'publishable'))
